"""
MESE-CR — M4 (part 4): merge easy + hard into the runnable dataset.py
=====================================================================
Sources:
  easy.csv  — 740 template sentences (polarity guaranteed by construction,
              no review needed). Written by dataset_templates.py.
  hard.csv  — 144 curated hard-context sentences, audited clean by
              dataset_hard.py. (Default)

Legacy path kept: --review dataset_review.csv merges the LLM-drafted hard
candidates you reviewed by hand (only rows with an empty 'flag' column).

Everything passes one final gate before it is written:
  * HARD rows must survive leak_lexicon.reason_to_reject() (no leakage word,
    concrete, right length) — otherwise the hard/easy contrast is a lie
  * labels one-hot, polarity +-1
  * no duplicate sentences
The output dataset.py keeps the 3-tuple DATA format the pipeline steps import,
and adds GROUPS (aligned list of template/motif keys) for grouped CV.
"""
import csv, shutil, os, sys, argparse
from collections import Counter
from leak_lexicon import AXES, reason_to_reject

def _norm(s):
    return " ".join(s.lower().split())

def load(path):
    with open(path, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))

def collect(review_path=None):
    """Return (rows, rejected, source_counts); rows = (sentence, [V,A,C,F], kind, group)."""
    easy = load("easy.csv")
    if review_path:
        hard_src = "review:" + review_path
        drafts = load(review_path)
        hard = [r for r in drafts if not (r.get("flag") or "").strip()]
        for r in hard:
            r.setdefault("group", "draft|" + _norm(r["sentence"])[:40])
    else:
        hard_src = "curated hard.csv"
        hard = load("hard.csv") if os.path.exists("hard.csv") else None
        if hard is None:
            import dataset_hard
            hard = []
            for row in dataset_hard.build_hard():
                s, v, a, c, f, kind, group = row
                hard.append({"sentence": s, "V": v, "A": a, "C": c, "F": f, "group": group})
    return easy, hard, hard_src

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--review", default=None, help="use a hand-reviewed draft CSV instead of curated hard.csv")
    ap.add_argument("--out", default="dataset.py")
    args = ap.parse_args()

    easy, hard, hard_src = collect(args.review)
    print(f"easy: {len(easy)}   hard source: {hard_src}   hard input: {len(hard)}")

    rows, rejected, seen = [], [], {}
    for src, recs, kind in (("easy", easy, "easy"), (hard_src, hard, "hard")):
        for r in recs:
            s = r["sentence"].strip()
            vals = [int(r[k]) for k in "VACF"]
            group = r.get("group") or f"{kind}|{_norm(s)[:40]}"
            # --- gate ---
            problems = []
            if kind == "hard":
                problems += reason_to_reject(s)
            if sum(1 for v in vals if v != 0) != 1:
                problems.append(f"label not one-hot: {vals}")
            elif next(v for v in vals if v != 0) not in (1, -1):
                problems.append(f"polarity not +-1: {vals}")
            if _norm(s) in seen:
                problems.append(f"duplicate of: {seen[_norm(s)][:60]}")
            if problems:
                rejected.append((kind, s, "; ".join(problems)))
                continue
            seen[_norm(s)] = s
            rows.append((s, vals, kind, group))

    if rejected:
        print(f"\nGATE REJECTED {len(rejected)} row(s):")
        for kind, s, why in rejected[:30]:
            print(f"  [{kind}] {why}  | {s[:70]}")

    import random; random.Random(0).shuffle(rows)
    if os.path.exists(args.out):
        shutil.copy(args.out, args.out + ".bak")
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("# Auto-generated by dataset_merge.py — DO NOT EDIT BY HAND\n")
        f.write("# DATA = [(sentence, [V,A,C,F], 'easy'|'hard'), ...]\n")
        f.write("# GROUPS[i] = template/motif key of DATA[i]  -> use for grouped CV\n")
        f.write("DATA = [\n")
        for s, labs, kind, _g in rows:
            f.write(f"    ({s!r}, {labs!r}, {kind!r}),\n")
        f.write("]\n\nGROUPS = [\n")
        for _s, _labs, _kind, g in rows:
            f.write(f"    {g!r},\n")
        f.write("]\n")
    print(f"\nWROTE {args.out} with {len(rows)} sentences "
          f"({sum(1 for r in rows if r[2] == 'hard')} hard, {len({r[3] for r in rows})} groups)")
    for ax, key in enumerate("VACF"):
        c = Counter(r[1][ax] for r in rows)
        print(f"  axis {key}: {dict(sorted(c.items()))}")

if __name__ == "__main__":
    main()
